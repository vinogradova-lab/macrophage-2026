    'incubated for 5 min at room temperature. Cells were then diluted with PBS, pelleted (520 x '
    'g, 25 °C, 8 min), and washed with PBS. PBMCs were resuspended at 50 × 10⁶ cells /mL, and '
    'monocytes were isolated by negative selection using the EasySep Monocyte Enrichment Kit '
    'without CD16 Depletion (STEMCELL Technologies) according to manufacturer’s instructions.'
