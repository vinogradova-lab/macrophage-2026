    'Peripheral blood was diluted with PBS, and 25 mL of the diluted cells were layered over 12.5 '
    'mL of Lymphoprep (STEMCELL Technologies) using 50 mL Falcon tubes. Tubes were centrifuged at '
    'room temperature (900 x g, 25 °C, 20 min) with the acceleration set to 50% and brake '
